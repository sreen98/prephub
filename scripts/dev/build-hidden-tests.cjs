// Usage: node scripts/dev/build-hidden-tests.cjs <verified.json>...
// Merges verified hidden-test files (from verify-hidden-tests.cjs) into
// src/data/playground/challengeHiddenTests.ts, in the playground's challenge order.
const fs = require('fs'), path = require('path');
const REPO = path.resolve(__dirname, '../..');
const index = JSON.parse(fs.readFileSync(path.join(REPO, 'src/generated/playground-index.json'), 'utf8'));
const order = index.categories.filter((c) => c.kind === 'challenge' && c.tag === 'JS').flatMap((c) => c.templates.map((t) => t.name));
const merged = {};
for (const f of process.argv.slice(2)) Object.assign(merged, JSON.parse(fs.readFileSync(f, 'utf8')));
const names = [...order.filter((n) => merged[n]), ...Object.keys(merged).filter((n) => !order.includes(n))];
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(merged[n], null, 2).replace(/\n/g, '\n  ')},`).join('\n');
fs.writeFileSync(path.join(REPO, 'src/data/playground/challengeHiddenTests.ts'), `// GENERATED by scripts/dev/build-hidden-tests.cjs from verified test files.
// Each \`output\` is what the reference solution prints for \`run\`;
// challengeHiddenTests.test.ts re-derives every one on each build.
// See src/lib/hiddenTests.ts for what a hidden test is.

export interface HiddenTestData {
  label: string;
  run: string;
  output: string;
  waitMs?: number;
}

export const challengeHiddenTests: Record<string, HiddenTestData[]> = {
${body}
};
`);
console.log(`wrote ${names.length} challenges, ${names.reduce((a, n) => a + merged[n].length, 0)} tests`);
